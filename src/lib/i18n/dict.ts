export type Locale = "en" | "ar";
export type Key = keyof Dict;
export const DICTS: Record<Locale, Dict> = { en, ar };

export function translate(locale: Locale, key: Key, vars?: Record<string, string | number>) {
  let s: string = DICTS[locale][key] ?? en[key];
  for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, String(v));
  return s.replaceAll("{brand}", DICTS[locale].brand);
}
